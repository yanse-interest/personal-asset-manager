import { readFile, writeFile } from 'node:fs/promises';
import * as lucide from 'lucide-react';

const converted = JSON.parse(await readFile(new URL('../src/domain/convertedLineArt.json', import.meta.url), 'utf8'));
const additional = JSON.parse(await readFile(new URL('../src/domain/additionalLineIcons.json', import.meta.url), 'utf8'));
const slug = value => value.toLowerCase().replaceAll(' ', '_');
const entries = [
  ...Object.entries(converted).map(([name, component]) => [slug(name), component]),
  ...Object.values(additional).flatMap(choices => choices.map(([value, , component]) => [value, component])),
];
const invalid = entries.filter(([, component]) => !lucide[component]);
if (invalid.length) throw new Error(`Unknown Lucide components: ${JSON.stringify(invalid)}`);
const components = [...new Set(entries.map(([, component]) => component))].sort();
const output = [
  '// Generated by scripts/generate-outline-components.mjs. Edit the JSON catalogs instead.',
  "import type { ComponentType } from 'react';",
  `import { ${components.join(', ')} } from 'lucide-react';`,
  '',
  'export const outlineComponents: Record<string, ComponentType<{ size?: number; strokeWidth?: number }>> = {',
  ...entries.map(([value, component]) => `  ${JSON.stringify(value)}: ${component},`),
  '};',
  '',
].join('\n');
await writeFile(new URL('../src/components/OutlineComponents.ts', import.meta.url), output);
console.log(`Generated ${entries.length} icon mappings from ${components.length} Lucide drawings.`);
